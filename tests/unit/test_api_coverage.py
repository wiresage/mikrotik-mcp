def _load_module():
    spec = importlib.util.spec_from_file_location("api_coverage", SCRIPT)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


api_coverage = _load_module()


def _manifest_with(menus, sections=None, excluded=None, server_tools=None):
    if sections is None:
        sections = [api_coverage.Section(title="Test", menus=list(menus))]
    return api_coverage.CoverageManifest(
        sections=sections,
        menus=menus,
        server_tools=server_tools or {},
        excluded=excluded or [],
    )


def _menu(title, section, commands, **kwargs):
    return api_coverage.MenuCoverage(
        title=title,
        section=section,
        commands=commands,
        **kwargs,
    )


def _command(status="implemented", tools=None, params=None, **kwargs):
    if tools is None:
        tools = ["some_tool"] if status == "implemented" else []
    return api_coverage.CommandCoverage(
        status=status,
        tools=tools,
        params=params if params is not None else [],
        **kwargs,
    )


def _lock():
    return api_coverage.ManualLock(
        version="test",
        url="",
        etag="",
        sha256="0" * 64,
        built_at="",
    )


