def test_main_reports_manifest_errors_before_loading_the_tool_catalogue(
    tmp_path,
    monkeypatch,
    capsys,
):
    """A structural manifest error must not be masked by a catalogue failure."""
    manifest_path = tmp_path / "api-coverage.yml"
    manifest_path.write_text(
        "sections:\n"
        "  - title: Test\n"
        "    menus: ['/missing']\n"
        "menus: {}\n"
        "server_tools: {}\n"
        "excluded: []\n",
        encoding="utf-8",
    )

    def fail_if_called():
        raise AssertionError("the tool catalogue must not be loaded")

    monkeypatch.setattr(api_coverage, "load_tool_names", fail_if_called)

    exit_code = api_coverage.main(
        [
            "--manifest",
            str(manifest_path),
            "--lock",
            str(api_coverage.DEFAULT_LOCK),
            "--output",
            str(tmp_path / "api-coverage.md"),
        ],
    )

    captured = capsys.readouterr()
    assert exit_code == 1
    assert "manifest errors:" in captured.err
    assert "/missing: listed in section 'Test' but missing from menus" in captured.err
    assert "tool catalogue" not in captured.err


